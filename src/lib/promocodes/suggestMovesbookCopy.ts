export function getSuggestMovesbookCopy(language: string): SuggestMovesbookCopy {
  const code = (language || 'en').toLowerCase().slice(0, 2);
  if (code === 'it') return IT;
  if (code === 'fr') return FR;
  if (code === 'de') return DE;
  if (code === 'es') return ES;
  return EN;
}

export function stripStoredHtml(value: string): string {
  return value
    .replace(/<br\s*\/?>/gi, '\n')
    .replace(/<\/p>/gi, '\n')
    .replace(/<[^>]+>/g, '')
    .replace(/&nbsp;/gi, ' ')
    .replace(/&amp;/gi, '&')
    .replace(/&lt;/gi, '<')
    .replace(/&gt;/gi, '>')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}
