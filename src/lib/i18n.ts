    // Get string by key
    t(key: string): string {
      // If key is marked as deleted, return the variable name itself
      if (this.deletedKeys.has(key)) {
        return key;
      }
      
      const currentLang = this.languages.find(lang => lang.code === this.currentLanguage);
      return currentLang?.strings[key] || this.languages[0]?.strings[key] || key;
    }
    
    /** Overlays strings from the Section languages (DB) on a built-in language. */
    mergeStrings(code: string, strings: Record<string, string>) {
      const lang = this.languages.find(l => l.code === code);
      if (lang) Object.assign(lang.strings, strings);
    }

    // Add new language
    addLanguage(language: Language) {
      this.languages.push(language);
    }
    
    // Set current language
    setLanguage(code: string) {
      this.currentLanguage = code;
    }
    
    // Get all languages
    getLanguages(): Language[] {
      return this.languages;
    }
    
    // Long texts management
    addLongText(longText: LongText) {
      this.longTexts.push(longText);
    }
    
    getLongTexts(): LongText[] {
      return this.longTexts;
    }
    
    getLongText(variable: string, languageCode?: string): string {
      const text = this.longTexts.find(t => t.variable === variable);
      const lang = languageCode || this.currentLanguage;
      return text?.content[lang] || text?.content['en'] || variable;
    }
    
    // Get default English strings (public method)
    getDefaultEnglishStrings(): LanguageStrings {
      return getDefaultEnglishStrings();
    }
