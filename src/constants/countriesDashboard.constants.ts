function primaryLanguageFor(iso: string, officialLanguage: string): string {
  if (['US', 'GB', 'CA', 'AU', 'NZ', 'IE', 'IN', 'PK', 'BD', 'NG', 'KE', 'ZA', 'SG'].includes(iso)) {
    return 'English';
  }
  if (['FR', 'BE', 'CH', 'LU', 'MC', 'SN', 'ML', 'BF', 'NE', 'TG', 'BJ', 'CI'].includes(iso)) {
    return 'French';
  }
  if (
    ['DE', 'AT', 'LI'].includes(iso) ||
    ['German', 'Austrian'].some((l) => officialLanguage.includes(l))
  ) {
    return 'German';
  }
  if (
    ['ES', 'MX', 'AR', 'CO', 'CL', 'PE', 'VE', 'EC', 'BO', 'PY', 'UY', 'CR', 'PA', 'SV', 'GT', 'HN', 'NI', 'DO', 'CU'].includes(
      iso,
    )
  ) {
    return 'Spanish';
  }
  if (['BR', 'PT', 'AO', 'MZ', 'CV', 'ST', 'TL', 'GW'].includes(iso)) {
    return 'Portuguese';
  }
  if (['RU', 'BY', 'KZ', 'KG', 'UA'].includes(iso)) {
    return 'Russian';
  }
  if (['CN', 'TW'].includes(iso)) {
    return 'Chinese';
  }
  if (iso === 'JP') return 'Japanese';
  if (
    ['SA', 'EG', 'IQ', 'SY', 'JO', 'LB', 'KW', 'QA', 'BH', 'OM', 'YE', 'LY', 'TN', 'DZ', 'MA', 'SD', 'AE', 'PS'].includes(
      iso,
    )
  ) {
    return 'Arabic';
  }
  if (['IT', 'SM', 'VA'].includes(iso)) return 'Italian';
  return officialLanguage;
}

function secondaryLanguageFor(iso: string, primaryLanguage: string): string {
  if (primaryLanguage === 'English') {
    if (['IN', 'PK', 'BD'].includes(iso)) return 'Hindi';
    if (['BH', 'AE', 'QA', 'KW'].includes(iso)) return 'Urdu';
    return 'French';
  }
  if (primaryLanguage === 'French') return 'English';
  if (primaryLanguage === 'Spanish') {
    if (['AR', 'UY'].includes(iso)) return 'Italian';
    return 'English';
  }
  if (primaryLanguage === 'Arabic') return 'French';
  if (primaryLanguage === 'German') return 'English';
  if (primaryLanguage === 'Russian') return 'English';
  if (primaryLanguage === 'Chinese') return 'English';
  if (primaryLanguage === 'Portuguese') return 'English';
  return '—';
}

function regionCountFor(name: string): number {
  const regions = REGIONS_BY_COUNTRY[name];
  if (regions?.length) return regions.length;
  return 0;
}

function buildCountryRow(name: string, id: number): CountryRow {
  const override = COUNTRY_ROW_OVERRIDES[name];
  if (override) {
    return { id, name, ...override, ...marketRates(override.currencyCode) };
  }

  const iso = COUNTRY_CODE_MAP[name] ?? name.slice(0, 2).toUpperCase();
  const iso2 = iso.toLowerCase();
  const officialLanguage = OFFICIAL_LANGUAGE_BY_ISO[iso] ?? name;
  const primaryLanguage = primaryLanguageFor(iso, officialLanguage);
  const secondaryLanguage = secondaryLanguageFor(iso, primaryLanguage);
  const currencyCode = CURRENCY_BY_ISO[iso] ?? 'USD';
  const eurUsesEuro = currencyCode === 'EUR';

  return {
    id,
    name,
    iso2,
    continent: CONTINENT_BY_ISO[iso] ?? 'West Europe',
    population: POPULATION_BY_ISO[iso] ?? 0,
    officialLanguage,
    primaryLanguage,
    secondaryLanguage,
    eurRate: eurUsesEuro ? 1 : 1.08,
    usdRate: currencyCode === 'USD' ? 1 : 1.08,
    ...marketRates(currencyCode),
    currencyCode,
    regions: regionCountFor(name),
  };
}

export const COUNTRIES_DASHBOARD_ROWS: CountryRow[] = COUNTRIES.map((name, index) =>
  buildCountryRow(name, index + 1),
);

/** Built-in currency of a country and its 1 EUR rate when known (placeholder rates excluded). */
export function builtInCountryCurrency(
  name: string,
): { currencyCode: string; eurToLocal: number | null; usdToLocal: number | null } | null {
  const key = name.trim().toLowerCase();
  const row = COUNTRIES_DASHBOARD_ROWS.find((r) => r.name.toLowerCase() === key);
  if (!row) return null;
  const hasRealRates = marketRates(row.currencyCode) !== null;
  return {
    currencyCode: row.currencyCode,
    eurToLocal: hasRealRates ? row.eurRate : null,
    usdToLocal: hasRealRates ? row.usdRate : null,
  };
}

